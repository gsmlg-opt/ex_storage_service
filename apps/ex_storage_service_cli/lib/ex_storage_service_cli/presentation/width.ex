  def length(text),
    do:
      text
      |> String.to_charlist()
      |> Enum.reduce(0, fn code, sum -> sum + width(code, 0, tuple_size(@ranges) - 1) end)

  defp width(_, low, high) when low > high, do: 1

  defp width(code, low, high) do
    middle = div(low + high, 2)
    {first, last} = elem(@ranges, middle)

    cond do
      code < first -> width(code, low, middle - 1)
      code > last -> width(code, middle + 1, high)
      true -> 2
    end
  end
