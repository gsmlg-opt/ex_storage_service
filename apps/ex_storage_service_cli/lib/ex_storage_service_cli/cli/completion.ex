defmodule ExStorageServiceCli.CLI.Completion do
  @moduledoc "Offline contextual bash, zsh and fish completions from the command registry."
  alias ExStorageServiceCli.{Error, CLI.Registry}

  def generate(shell) when shell in ~w(bash zsh fish) do
    nodes = nodes()
    {:ok, if(shell == "fish", do: fish(nodes), else: posix(nodes, shell))}
  end

  def generate(_),
    do: {:error, Error.new(:syntax, "Completion shell must be bash, zsh or fish")}

  defp nodes do
    frontends = [:native, :s3, :s3api]
    root_scan = Enum.reduce(frontends, %{}, &Map.merge(&2, Registry.options(&1)))

    for frontend <- frontends,
        commands = Registry.commands(frontend),
        path <-
          [
            []
            | Enum.flat_map(Map.keys(commands), fn path ->
                for n <- 1..length(path), do: Enum.take(path, n)
              end)
          ]
          |> Enum.uniq(),
        into: %{} do
      {_, flags, _} = Registry.spec(frontend, path)
      flags = Map.merge(Registry.globals(frontend), flags)

      children =
        commands
        |> Map.keys()
        |> Enum.filter(&(length(&1) > length(path) && Enum.take(&1, length(path)) == path))
        |> Enum.map(&Enum.at(&1, length(path)))
        |> then(&if(frontend == :native && path == [], do: &1 ++ ~w(s3 s3api), else: &1))
        |> Enum.uniq()
        |> Enum.sort()

      scan =
        cond do
          frontend == :native && path == [] -> root_scan
          Map.has_key?(commands, path) -> flags
          true -> Registry.options(frontend)
        end

      {node(frontend, path),
       %{
         frontend: frontend,
         path: path,
         children: children,
         options: expand(flags, frontend),
         scan: expand(scan, frontend)
       }}
    end
  end

  defp expand(flags, frontend) do
    flags
    |> Enum.reduce(%{}, fn {name, {_, type}}, acc ->
      kind =
        case type do
          :boolean -> "none"
          {:flag, _} -> "none"
          :optional -> "optional"
          {:optional_string, _, _} -> "optional"
          _ -> "required"
        end

      values =
        case type do
          {:enum, choices} -> choices
          {:optional_string, _, choices} -> choices
          :optional -> ~w(input output yaml-input)
          _ -> []
        end

      acc = Map.put(acc, "--" <> name, {kind, values})

      acc =
        if type == :boolean && !String.starts_with?(name, "no-") &&
             (frontend != :s3api || !Map.has_key?(Registry.globals(:s3api), name)),
           do: Map.put(acc, "--no-" <> name, {"none", []}),
           else: acc

      Enum.reduce(Registry.short_options(), acc, fn {short, long}, acc ->
        if frontend != :s3api && name == long,
          do: Map.put(acc, "-" <> short, {kind, values}),
          else: acc
      end)
    end)
  end

  defp node(frontend, path), do: Enum.join([to_string(frontend) | path], "/")
  defp next("native", child) when child in ~w(s3 s3api), do: child
  defp next(key, child), do: key <> "/" <> child
  defp shell_quote(value), do: "'" <> String.replace(value, "'", "'\\''") <> "'"
  defp lines(values), do: Enum.join(values, "\n")

  defp posix(nodes, shell) do
    data = """
    # Generated by ess completion #{shell}; no config, credentials or network lookup.
    __ess_node() {
      ess_children=''; ess_options=''
      case "$1" in
    #{Enum.map_join(Enum.sort(nodes), "\n", fn {key, node} -> "    #{shell_quote(key)}) ess_children=#{shell_quote(lines(node.children))}; ess_options=#{shell_quote(lines(node.options |> Map.keys() |> Enum.sort()))} ;;" end)}
      esac
    }
    __ess_next() {
      ess_next="$1"
      case "$1:$2" in
    #{Enum.map_join(Enum.sort(nodes), "\n", fn {key, node} -> Enum.map_join(node.children, "\n", fn child -> "    #{shell_quote(key <> ":" <> child)}) ess_next=#{shell_quote(next(key, child))} ;;" end) end)}
      esac
    }
    __ess_flag() {
      ess_kind='none'; ess_values=''
      case "$1:$2" in
    #{flag_groups(nodes, fn patterns, kind, values -> "    #{Enum.map_join(patterns, "|", &shell_quote/1)}) ess_kind=#{shell_quote(kind)}; ess_values=#{shell_quote(lines(values))} ;;" end)}
      esac
    }
    """

    data <>
      """
      __ess_candidates() {
        local ess_current="$1" ess_state='native' ess_pending='' ess_pending_state=''
        local ess_position=0 ess_terminated=0 ess_word ess_flag ess_kind ess_values
        local ess_children ess_options ess_next ess_choices='' ess_prefix=''
        shift
        for ess_word in "$@"; do
          if [ -n "$ess_pending" ]; then
            __ess_flag "$ess_pending_state" "$ess_pending"
            if [ "$ess_kind" != optional ] || [ "${ess_word#-}" = "$ess_word" ]; then
              ess_pending=''; continue
            fi
            ess_pending=''
          fi
          if [ "$ess_terminated" = 1 ]; then continue; fi
          if [ "$ess_word" = -- ]; then ess_terminated=1; continue; fi
          case "$ess_word" in
            -*)
              ess_flag="${ess_word%%=*}"
              __ess_flag "$ess_state" "$ess_flag"
              if [ "$ess_kind" != none ] && [ "$ess_word" = "$ess_flag" ]; then
                ess_pending="$ess_flag"; ess_pending_state="$ess_state"
              fi
              ;;
            *)
              if [ "$ess_position" = 0 ]; then
                __ess_next "$ess_state" "$ess_word"
                if [ "$ess_next" = "$ess_state" ]; then ess_position=1; else ess_state="$ess_next"; fi
              fi
              ;;
          esac
        done
        if [ "$ess_terminated" = 1 ]; then return; fi
        if [ -n "$ess_pending" ]; then
          __ess_flag "$ess_pending_state" "$ess_pending"
          if [ "$ess_kind" != optional ] || [ "${ess_current#-}" = "$ess_current" ]; then
            ess_choices="$ess_values"
          else
            __ess_node "$ess_state"; ess_choices="$ess_options"
          fi
        else
          case "$ess_current" in
            --*=*)
              ess_flag="${ess_current%%=*}"
              __ess_flag "$ess_state" "$ess_flag"
              ess_choices="$ess_values"; ess_prefix="$ess_flag="; ess_current="${ess_current#*=}"
              ;;
            -*) __ess_node "$ess_state"; ess_choices="$ess_options" ;;
            *)
              __ess_node "$ess_state"
              if [ "$ess_position" = 0 ]; then ess_choices="$ess_children"; fi
              if [ -z "$ess_current" ]; then ess_choices="$ess_choices
      $ess_options"; fi
              ;;
          esac
        fi
        printf '%s\n' "$ess_choices" | while IFS= read -r ess_word; do
          [ -n "$ess_word" ] || continue
          case "$ess_word" in "$ess_current"*) printf '%s\n' "$ess_prefix$ess_word" ;; esac
        done
      }
      """ <> wrapper(shell)
  end

  defp wrapper("bash") do
    """
    _ess_complete() {
      local candidate
      COMPREPLY=()
      while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(
        __ess_candidates "${COMP_WORDS[COMP_CWORD]-}" "${COMP_WORDS[@]:1:COMP_CWORD-1}"
      )
    }
    complete -F _ess_complete ess
    """
  end

  defp wrapper("zsh") do
    """
    _ess_complete() {
      local -a suggestions
      if (( CURRENT > 2 )); then
        suggestions=("${(@f)$(__ess_candidates "$words[CURRENT]" "${(@)words[2,CURRENT-1]}")}")
      else
        suggestions=("${(@f)$(__ess_candidates "$words[CURRENT]")}")
      fi
      (( ${#suggestions} )) && compadd -- "${suggestions[@]}"
    }
    compdef _ess_complete ess
    """
  end

  defp flag_groups(nodes, render) do
    nodes
    |> Enum.flat_map(fn {key, node} ->
      Enum.map(node.scan, fn {flag, spec} -> {spec, key <> ":" <> flag} end)
    end)
    |> Enum.group_by(&elem(&1, 0), &elem(&1, 1))
    |> Enum.sort()
    |> Enum.map_join("\n", fn {{kind, values}, patterns} ->
      render.(Enum.sort(patterns), kind, values)
    end)
  end

  defp fish(nodes) do
    """
    # Generated by ess completion fish; no config, credentials or network lookup.
    function __ess_node
      switch $argv[1]
    #{Enum.map_join(Enum.sort(nodes), "\n", fn {key, node} -> "    case #{shell_quote(key)}\n      printf '%s\\n' " <> Enum.map_join(node.children ++ (Map.keys(node.options) |> Enum.sort()), " ", &shell_quote/1) end)}
      end
    end
    function __ess_next
      switch "$argv[1]:$argv[2]"
    #{Enum.map_join(Enum.sort(nodes), "\n", fn {key, node} -> Enum.map_join(node.children, "\n", fn child -> "    case #{shell_quote(key <> ":" <> child)}\n      printf '%s\\n' #{shell_quote(next(key, child))}; return" end) end)}
      end
      printf '%s\\n' "$argv[1]"
    end
    function __ess_flag
      switch "$argv[1]:$argv[2]"
    #{flag_groups(nodes, fn patterns, kind, values -> "    case #{Enum.map_join(patterns, " ", &shell_quote/1)}\n      printf '%s\\n' #{Enum.map_join([kind | values], " ", &shell_quote/1)}; return" end)}
      end
      printf '%s\\n' none
    end
    function __ess_candidates
      set -l current "$argv[1]"
      set -l state native
      set -l pending ''
      set -l pending_state ''
      set -l position 0
      set -l terminated 0
      for word in $argv[2..-1]
        if test -n "$pending"
          set -l meta (__ess_flag "$pending_state" "$pending")
          if test "$meta[1]" != optional; or not string match -q -- '-*' "$word"
            set pending ''; continue
          end
          set pending ''
        end
        if test $terminated = 1; continue; end
        if test "$word" = --; set terminated 1; continue; end
        if string match -q -- '-*' "$word"
          set -l flag (string split -m 1 = -- "$word")[1]
          set -l meta (__ess_flag "$state" "$flag")
          if test "$meta[1]" != none; and test "$word" = "$flag"
            set pending "$flag"; set pending_state "$state"
          end
        else if test $position = 0
          set -l next (__ess_next "$state" "$word")
          if test "$next" = "$state"; set position 1; else; set state "$next"; end
        end
      end
      if test $terminated = 1; return; end
      set -l choices
      set -l prefix ''
      if test -n "$pending"
        set -l meta (__ess_flag "$pending_state" "$pending")
        if test "$meta[1]" != optional; or not string match -q -- '-*' "$current"
          set choices $meta[2..-1]
        else
          set choices (__ess_node "$state" | string match -- '-*')
        end
      else if string match -q -- '--*=*' "$current"
        set -l split (string split -m 1 = -- "$current")
        set -l meta (__ess_flag "$state" "$split[1]")
        set choices $meta[2..-1]; set prefix "$split[1]="; set current "$split[2]"
      else
        set choices (__ess_node "$state")
        if string match -q -- '-*' "$current"
          set choices (printf '%s\\n' $choices | string match -- '-*')
        else if test -n "$current"; and test $position = 1
          return
        else if test -n "$current"
          set choices (printf '%s\\n' $choices | string match -v -- '-*')
        else if test $position = 1
          set choices (printf '%s\\n' $choices | string match -- '-*')
        end
      end
      for candidate in $choices
        if test (string sub -l (string length -- "$current") -- "$candidate") = "$current"
          printf '%s\\n' "$prefix$candidate"
        end
      end
    end
    function __ess_complete
      set -l words (commandline -opc)
      set -l current (commandline -ct)
      if test -n "$current"; and test (count $words) -gt 1; and test "$words[-1]" = "$current"
        set -e words[-1]
      end
      __ess_candidates "$current" $words[2..-1]
    end
    complete -c ess -f -a '(__ess_complete)'
    """
  end
end
